"""Generate every current curriculum view from syllabus/course.yml.

Use --check to detect drift without writing. Policy wording has one source in
syllabus/policies.md. Historical snapshots and teaching assets are never edited.
"""
from __future__ import annotations

import argparse
from datetime import date, timedelta
import json
import os
from pathlib import Path
import re
import sys

import yaml
import session_pages
import assignment_briefs
import course_deadlines
from output_files import write_text

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "syllabus/course.yml"
MARKER = "<!-- Generated by scripts/sync_course.py from syllabus/course.yml and syllabus/policies.md. Edit the sources, not this copy. -->"
BASE = "{{ site.baseurl }}"


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def bullets(items):
    return "\n".join(f"- {x}" for x in items) + "\n"


def table(headers, rows):
    def row(values):
        return "| " + " | ".join(str(x).replace("|", "\\|").replace("\n", " ") for x in values) + " |"
    return "\n".join([row(headers), row(["---"] * len(headers))] + [row(r) for r in rows]) + "\n"


def front(title, layout="course_page", **other):
    data = {"title": title, "layout": layout, "published": True, **other}
    return "---\n" + yaml.safe_dump(data, allow_unicode=True, sort_keys=False).strip() + "\n---\n\n" + MARKER + "\n\n"


class Course:
    def __init__(self):
        self.data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
        self.meta = self.data["course"]
        self.weeks = {x["week"]: x for x in self.data["weeks"]}
        self.units = {x["id"]: x for x in self.data["units"]}
        self.projects = {x["id"]: x for x in self.data["projects"]}
        self.assignments = []
        for p in self.projects.values():
            for a in p["milestones"]:
                a["project"] = p["id"]
                self.assignments.append(a)
        self.assessments = self.assignments + self.data["assessments"]
        self.by_id = {x["id"]: x for x in self.assessments}
        self.policy = (ROOT / "syllabus/policies.md").read_text(encoding="utf-8").strip()
        self.blender = self.data.get("blender", {})
        self.blender_images = json.loads((ROOT / "_data/blender_images.json").read_text(encoding="utf-8"))
        self.sessions = self.blender.get("sessions", [])
        self.sequence = self.data["teaching_sequence"]
        self.optional_classes = self.data.get('optional_classes', [])
        self.apply_sequence()
        self.unit_sessions = {}
        for s in self.sessions:
            for uid in s.get("units", []):
                self.unit_sessions.setdefault(uid, []).append(s)
        self.load_release()
        self.outputs = {}
        self.validate()
        assignment_briefs.validate(self)
        course_deadlines.validate(self)

    def apply_sequence(self):
        """One approved sequence owns weeks and session/lesson membership."""
        self.week_blocks = {}
        self.session_blocks = {}
        sessions = {s["id"]: s for s in self.sessions}
        assert len({b["id"] for b in self.sequence}) == len(self.sequence), "Duplicate teaching block"
        ordered_weeks = [w for b in self.sequence for w in b["weeks"]]
        assert ordered_weeks == list(self.weeks), "Teaching blocks must cover all weeks once, in order"
        optional_ids = [s for b in self.optional_classes for s in b['sessions']]
        ordered_sessions = [s for b in self.sequence for s in b["sessions"]]
        assert ordered_sessions == [sid for sid in sessions if sid not in optional_ids], "Required files must follow the teaching order"
        assert len(ordered_sessions + optional_ids) == len(set(ordered_sessions + optional_ids)) == len(sessions), "Every file belongs to one required or optional block"
        for block in self.optional_classes:
            assert block['optional'] and not block['weeks'], 'Optional classes have no required teaching week'
            assert all(self.units[u].get('optional') for u in block['units'])
        for block in self.sequence + self.optional_classes:
            assert block["focus"] and all(u in self.units for u in block["units"]), block["id"]
            scheduled = block.get('sessions_by_week')
            if scheduled is not None:
                assert set(scheduled) == set(block['weeks']), 'Schedule every week in the teaching block'
                assert not block.get('combine_sessions'), 'Combined sessions share one lesson'
                assert all(isinstance(sids, list) and sids for sids in scheduled.values())
                assert {sid for sids in scheduled.values() for sid in sids} == set(block['sessions']), 'Weekly sessions must match their teaching block'
            for sid in block["sessions"]:
                assert "units" not in sessions[sid], "Set session membership in teaching_sequence only"
                sessions[sid]["units"] = list(block["units"])
                self.session_blocks[sid] = block
                sessions[sid]['optional'] = bool(block.get('optional'))
            for i, number in enumerate(block["weeks"]):
                week = self.weeks[number]
                assert not {"title", "units", "sessions"} & set(week), "Set week topics in teaching_sequence only"
                week["title"] = block["focus"]
                week["units"] = list(block["units"])
                # Two files over two target weeks advance in order; one file can continue.
                week["sessions"] = (list(scheduled[number]) if scheduled is not None else
                                    block['sessions'][:1] if block.get('combine_sessions') else
                                    [block["sessions"][i]] if len(block["sessions"]) == len(block["weeks"])
                                    else list(block["sessions"]))
                self.week_blocks[number] = block

    # ── Release control ────────────────────────────────────────────────
    # A page not released is not written and never linked. SYNC_RELEASE=all
    # publishes everything for a local preview without touching the source.

    def load_release(self):
        rel = self.data.get("release") or {}
        override = os.environ.get("SYNC_RELEASE", "").strip().lower()
        if override in ("all", "1", "true"):
            rel = {"classes": "all", "tutorials": "all", "assignments": "all"}
        elif override:
            raise SystemExit(f"SYNC_RELEASE must be 'all' if set, not {override!r}")
        self.open_weeks = self.released(rel.get("classes"), set(self.weeks))
        self.open_units = self.released(rel.get("tutorials"), set(self.units) | {"TRANSLATION"})
        listed = rel.get("assignments")
        if isinstance(listed, list):
            # Milestones ride on their project page; naming one here would silently do nothing.
            wrong = {a["id"] for a in self.assignments} & set(listed)
            assert not wrong, ("release.assignments takes the project id, not a milestone: list "
                               f"{sorted({self.by_id[a]['project'] for a in wrong})} "
                               f"instead of {sorted(wrong)}")
        self.open_work = self.released(listed, set(self.projects) | set(self.by_id))

    @staticmethod
    def released(value, everything):
        if value is None or (isinstance(value, str) and value.strip().lower() == "all"):
            return set(everything)
        return set(value)

    def held(self, url):
        """True when url points at a page release control is holding back."""
        m = re.fullmatch(r"/classes/class-(\d+)/", url)
        if m:
            return int(m.group(1)) not in self.open_weeks
        m = re.fullmatch(r"/tutorials/(u\d+)-[a-z0-9\-]+/", url)
        if m:
            return m.group(1).upper() not in self.open_units
        if url == "/tutorials/translation-what-you-have-been-reading/":
            return "TRANSLATION" not in self.open_units
        # A milestone's anchor lives on its project page, so it is held with it.
        m = re.fullmatch(r"/assignments/([a-z0-9]+)-[a-z0-9\-]+/(#[a-z0-9]+)?", url)
        if m:
            return m.group(1).upper() not in self.open_work
        return False

    def validate(self):
        people = self.meta.get("instructors")
        assert isinstance(people, list) and people, "course.instructors must list at least one instructor"
        assert all(p.get("name") for p in people), "Every entry in course.instructors needs a name"
        assert "instructor" not in self.meta, "Retired: use the course.instructors list, not course.instructor"
        for group, items in self.data['decisions'].items():
            assert all(isinstance(x, str) for x in items), f"Quote colon-containing text in decisions.{group}"
        assert list(self.weeks) == list(range(1, 16)), "Expected 15 ordered weeks"
        dates = [date.fromisoformat(w["date"]) for w in self.weeks.values()]
        assert all(d.weekday() == 1 for d in dates), "Classes must be Tuesdays"
        assert all(b - a == timedelta(days=7) for a, b in zip(dates, dates[1:])), "Calendar is not weekly"
        assert len(self.by_id) == len(self.assessments), "Duplicate assignment identifier"
        assert sum(a["weight"] for a in self.assessments) == 100, "Weights must total 100%"
        for a in self.assessments:
            assert all(isinstance(x, str) for x in a['requirements']), f"Invalid requirement in {a['id']}"
            assert a["release"] in self.weeks
            assert a["due"] in self.weeks or a["due"] in ("final", "ongoing")
            if isinstance(a["due"], int):
                assert a["due"] >= a["release"], f"Deadline before release: {a['id']}"
                assert not self.weeks[a["due"]].get("no_due"), f"Submission in blackout week: {a['id']}"
            for c in a.get("checkpoints", []):
                assert set(c) == {'week', 'text'}, f"Quote comma-containing checkpoint text in {a['id']}"
                assert isinstance(c['text'], str)
                assert c["week"] in self.weeks or c["week"] == "final"
        for w in self.weeks.values():
            assert all(u in self.units for u in w["units"])
        for p in self.projects.values():
            assert all(u in self.units for u in p["units"])
            assert not any(self.units[u].get('optional') for u in p['units']), 'Required projects must not depend on optional intermediate classes'
        for u in self.units.values():
            assert all(isinstance(x, str) for x in u['steps']), f"Invalid step in {u['id']}"
            assert isinstance(u.get("pseudocode", ""), str), f"Invalid pseudocode in {u['id']}"
        seen = set()
        for s in self.sessions:
            assert s["id"] not in seen, f"Duplicate session identifier: {s['id']}"
            seen.add(s["id"])
            assert all(u in self.units for u in s["units"]), f"Unknown unit in {s['id']}"
            assert all(isinstance(x, str) for x in s["scenes"]), f"Quote comma-containing scene name in {s['id']}"
            for label, path in s.get("extras", []):
                assert isinstance(label, str) and isinstance(path, str), f"Invalid extra in {s['id']}"
        assert self.open_weeks <= set(self.weeks), f"release.classes lists an unknown week: {sorted(self.open_weeks - set(self.weeks))}"
        unknown = self.open_units - set(self.units) - {"TRANSLATION"}
        assert not unknown, f"release.tutorials lists an unknown unit: {sorted(unknown)}"
        unknown = self.open_work - set(self.projects) - set(self.by_id)
        assert not unknown, f"release.assignments lists an unknown assignment: {sorted(unknown)}"
        assert re.search(r"\*\*5% of the final grade", self.policy), "Reconcile attendance policy and grading"
        assert self.by_id["PART"]["weight"] == 5
        assert all(a.get('deliverable') for a in self.assignments), 'Every project assignment needs a presentation requirement'
        reviewed = self.data['presentation_review']
        assert [r['week'] for r in reviewed] == list(self.weeks), 'Review presentation coverage for every week'
        for r in reviewed:
            assert r['status'] in {'current', 'needs_revision', 'missing'} and r['note']
            assert r.get('publish', False) in (True, False), 'presentation_review.publish must be a boolean'
            if r.get('publish'):
                assert r['status'] != 'missing', 'Missing slides cannot be published'
            if r['status'] == 'current' or r.get('publish'):
                assert all((ROOT / 'slides' / f"ARC3133_Class{r['week']:02d}.{ext}").is_file() for ext in ('pptx', 'pdf')), 'Published slides need both formats'

    def emit(self, path, content):
        self.outputs[path] = content.rstrip() + "\n"

    def when(self, value):
        if value == "final":
            return "Final review — " + self.meta["final_window"]
        if value == "ongoing":
            return "Throughout the semester"
        d = date.fromisoformat(self.weeks[value]["date"])
        return f"Week {value} — {d.strftime('%b')} {d.day}"

    def due_time(self, assignment):
        return course_deadlines.time_label(self, assignment)

    def deadline(self, assignment):
        return course_deadlines.deadline(self, assignment)

    def midterm_note(self):
        return course_deadlines.note(self)

    def midterm_deadline(self):
        return course_deadlines.midterm_deadline(self)

    def midterm_summary(self, web=False):
        return course_deadlines.summary(self, web)

    @staticmethod
    def label(a):
        return a.get("number", a["id"]) + " — " + a["title"]

    def banner(self):
        """The instructor-facing notice. Syllabus and reference documents only."""
        return (f"> **{self.data['status']} · {self.data['revision']}.** The teaching sequence is "
                "flexible. Dates and weights below are a coordinated draft; outstanding instructor "
                "and administrative decisions are listed in the syllabus.\n\n")

    def notice(self):
        """What students see. A different audience deserves a different sentence."""
        text = (self.data.get("student_notice") or "").strip()
        return f"> {text}\n\n" if text else ""

    def project_url(self, p):
        p = self.projects[p] if isinstance(p, str) else p
        return f"/assignments/{p['id'].lower()}-{p.get('url_slug', slug(p['title']))}/"

    def assignment_url(self, a):
        if "project" in a:
            return self.project_url(a["project"]) + "#" + a["id"].lower()
        if a["id"] == "PART":
            return "/resources/course-policies/"
        return f"/assignments/{a['id'].lower()}-{a.get('url_slug', slug(a['title']))}/"

    def unit_url(self, u):
        return f"/tutorials/{u['id'].lower()}-{u.get('url_slug', slug(u['title']))}/"

    def link(self, text, url):
        if self.held(url):
            return f"{text} — *not yet released*"
        if url.startswith(("/assignments/", "/tutorials/", "/classes/")):
            url = "/modules" + url
        return f"[{text}]({BASE}{url})"

    def class_url(self, week):
        return f"/classes/class-{week:02d}/"

    def calendar(self, web=False):
        rows = []
        for w in self.weeks.values():
            due = [a for a in self.assessments if a["due"] == w["week"]]
            labels = [self.label(a) for a in due]
            if web:
                labels = [self.link(label, self.assignment_url(a)) for label, a in zip(labels, due)]
            labels = [label + (f" ({course_deadlines.short(self, a)})" if course_deadlines.short(self, a) else "") for label, a in zip(labels, due)]
            focus = w["title"]
            if w["week"] == self.meta.get("midterm_week"):
                early = any(course_deadlines.due_day(a) for a in due)
                focus = ("Midterm grade; " if early else "Midterm deadline and accumulated grade; ") + focus[0].lower() + focus[1:]
            rows.append([w["week"], self.when(w["week"]).split(" — ")[1], focus, "; ".join(labels) or ("No graded submission" if w.get("no_due") else "—")])
        final = [a for a in self.assessments if a["due"] == "final"]
        rows.append(["Final", self.meta["final_window"], "Final review", "; ".join(self.label(a) for a in final) + "; revised GSM"])
        return table(["Week", "Date", "Teaching focus", "Submissions"], rows)

    def assessment_table(self, web=False):
        rows = []
        for a in self.assessments:
            name = self.label(a)
            if web:
                name = self.link(name, self.assignment_url(a))
            rows.append([name, self.when(a["release"]), self.deadline(a), f"{a['weight']}%"])
        rows.append(["Total", "", "", "100%"])
        return table(["Assignment", "Introduced", "Due", "Weight"], rows)

    def project_table(self, web=False):
        rows = []
        for p in self.projects.values():
            title = p["id"] + " — " + p["title"]
            if web:
                title = self.link(title, self.project_url(p))
            rows.append([title, p["approach"], " → ".join(a["title"] for a in p["milestones"]), str(sum(a["weight"] for a in p["milestones"])) + "%"])
        return table(["Project", "Approach", "Assignments", "Weight"], rows)

    def assignment(self, a, heading="###", detailed=False):
        body = f"<a id=\"{a['id'].lower()}\"></a>\n\n{heading} {self.label(a)}\n\n"
        body += f"**Introduced:** {self.when(a['release'])} · **Due:** {self.deadline(a)} · **Weight:** {a['weight']}%\n\n"
        if a.get('deliverable'):
            body += '**Present:** ' + a['deliverable'] + '\n\n'
        body += assignment_briefs.body(a, heading + "#") if detailed and a.get("brief") else bullets(a["requirements"])
        if a.get("checkpoints"):
            body += "\n**Ungraded checkpoints:**\n\n"
            body += bullets([f"{self.when(c['week'])}: {c['text']}" for c in a["checkpoints"]])
        return body + "\n"

    def submission_table(self, web=False):
        rows = []
        for a in self.assignments:
            title = self.label(a)
            if web:
                title = self.link(title, self.assignment_url(a))
            rows.append([title, a['deliverable']])
        return table(['Assignment', 'Presentation and files'], rows)

    def unit(self, u, web=False):
        out = f"## {u['id']} — {u['title']}\n\n{u['goal']}\n\n"
        if u.get('optional'):
            out += '**Possible intermediate class — optional.** This topic is outside the required teaching sequence.\n\n'
        out += "**Vocabulary:** " + ", ".join(u["vocabulary"]) + ".\n\n"
        out += self.video_list(u, web)
        for block in self.sequence:
            if u['id'] in block['units']:
                classes = ' · '.join(self.link(f'Class {n:02d}', self.class_url(n)) for n in block['weeks'])
                out += ('**Taught in:** ' + classes + '. ' + (block.get('delivery') or '')).rstrip() + '\n\n'
        out += "\n".join(f"{i}. {step}" for i, step in enumerate(u["steps"], 1)) + "\n\n"
        out += "**Practice:** " + u["exercise"] + "\n\n**Use it next:** " + u["connection"] + "\n\n"
        if u.get("references"):
            group = self.data["references"][u["references"]]
            out += "**Examples to study:**\n\n" + bullets([f"[{a}]({b}) — {c}" for a,b,c in group]) + "\n"
        if "pseudocode" in u:
            out += "**Read the pseudocode.** Match each step to your nodes; you do not need to type it.\n\n"
            out += "```python\n" + u["pseudocode"].rstrip() + "\n```\n\n"
        if "teaching_note" in u and not web:  # instructor syllabus only
            out += "**Teaching note:** " + u["teaching_note"] + "\n\n"
        out += self.blender_files(u, web)
        if web and any(i["unit"] == u["id"] for i in self.blender_images):
            out += '## Examples from the class files\n\nSelect an image to inspect the original screenshot at full resolution.\n\n'
            out += '{% include blender_screenshots.html unit="' + u["id"] + '" %}\n\n'
        return out

    def video_list(self, u, web=False):
        vids = u.get('videos', [])
        if not vids:
            return '**Video tutorial:** not yet posted. Use the lesson notes and the class slides.\n\n'
        if web:
            return '**Video tutorials**\n\n' + self.video_embeds(u)
        return '**Video tutorials:** ' + ' · '.join(f'[{label}]({link})' for label, link in vids) + '\n\n'

    @staticmethod
    def youtube_id(link):
        """The video id from a youtu.be or youtube.com link, or None for anything else."""
        m = re.search(r'(?:youtu\.be/|youtube\.com/(?:watch\?v=|embed/|shorts/))([A-Za-z0-9_-]{11})', link)
        return m.group(1) if m else None

    def video_embeds(self, u):
        """Embedded players on web pages; anything that is not YouTube stays a link."""
        out = ''
        for label, link in u.get('videos', []):
            vid = self.youtube_id(link)
            title = f"{u['title']} — {label}"
            out += (f'{{% include youtube.html id="{vid}" title="{title}" %}}\n\n' if vid
                    else f'- Video tutorial — [{label}]({link})\n\n')
        return out

    def asset(self, path, web):
        """A repo-relative asset path as a URL for the site or for the repo tree."""
        return (BASE + "/" + path) if web else ("../" + path)

    def blender_files(self, u, web=False):
        """List the Blender sessions this unit uses. Only files actually on disk."""
        found = [s for s in self.unit_sessions.get(u["id"], []) if (ROOT / s["path"]).is_file()]
        if not found:
            return "**Lesson file:** To be prepared and verified.\n\n"
        out = "### Blender files for this lesson\n\n"
        out += (f"Prepared and evaluated in **{self.blender['version']}**. "
                f"{self.blender['version_note']} " + self.blender["how_to_use"] + "\n\n")
        out += self.blender['reference_note'] + '\n\n'
        for s in found:
            out += f"**{s['id']} — [{s['title']}]({self.asset(s['path'], web)})**\n\n"
            if web and session_pages.available(self, s):
                out += self.link('Open the class that teaches this file', session_pages.url(s, self)) + '\n\n'
            out += f"Scenes in this file: {', '.join(s['scenes'])}. "
            out += "Open them in the order listed.\n\n"
            if s.get("note"):
                out += s["note"].strip() + "\n\n"
            extras = [(label, path) for label, path in s.get("extras", []) if (ROOT / path).is_file()]
            if extras:
                out += "Supporting files: " + ", ".join(
                    f"[{label}]({self.asset(path, web)})" for label, path in extras) + ".\n\n"
        return out

    def translation(self, web=False):
        out = self.data["translation"] + "\n\n"
        for u in self.units.values():
            if "pseudocode" not in u:
                continue
            out += f"### {u['id']} — {u['title']}\n\n"
            out += "```python\n" + u["pseudocode"].rstrip() + "\n```\n\n"
            out += self.link("Back to the unit", self.unit_url(u).replace(BASE, "") if web else self.unit_url(u)) + "\n\n"
        return out

    def slides(self, week):
        """Link current decks and explicitly released older decks on weekly pages."""
        review = next((r for r in self.data['presentation_review'] if r['week'] == week), None)
        if review is None or (review['status'] != 'current' and not review.get('publish')):
            return 'Revised slides are not yet posted. Use the lesson notes and current assignment briefs.'
        stem = f"ARC3133_Class{week:02d}"
        found = [(label, f"/slides/{stem}{ext}")
                 for label, ext in (("PDF", ".pdf"), ("PowerPoint", ".pptx"))
                 if (ROOT / "slides" / (stem + ext)).is_file()]
        if not found:
            return ""
        links = " · ".join(self.link(label, url) for label, url in found)
        if review['status'] == 'needs_revision':
            return ("**Earlier slide deck — revision pending.** Follow this class page and the current assignment "
                    "briefs for requirements, deadlines and grading.\n\n" + links)
        return links

    def project_spine(self):
        """The four projects as the course's spine: what you do, what it ends in."""
        rows = []
        for p in self.projects.values():
            title = self.link(p["id"] + " — " + p["title"], self.project_url(p))
            rows.append([title, p["description"].strip().rstrip("."),
                         str(sum(a["weight"] for a in p["milestones"])) + "%"])
        return table(["Project", "What you do", "Weight"], rows)

    def sequence_table(self, web=True):
        """The approved teaching blocks, with practical files nested underneath."""
        return session_pages.sequence(self, web)

    def optional_summary(self):
        if not self.optional_classes:
            return ''
        return '## Possible intermediate class\n\n' + '\n\n'.join('**' + b['focus'] + '.** ' + b['description'] for b in self.optional_classes) + '\n\n'

    def latest_class(self):
        """A one-line pointer to the most recent posted class."""
        if not self.open_weeks:
            return ""
        n = max(self.open_weeks)
        w = self.weeks[n]
        name = w['title'] + (' — ' + w['label'] if w.get('label') else '')
        return ("**Latest posted class:** "
                + self.link(f"Class {n:02d} · {name}", self.class_url(n))
                + f" ({self.when(n)})\n\n**Coming up:**\n\n")

    def whats_next(self, limit=4, heading=True):
        """The next few deadlines, instead of the whole 16-row calendar.

        'Next' is measured from the most recently posted class, which is the only
        notion of 'now' this generator has. The full calendar keeps its home on
        the syllabus page, which is linked underneath.
        """
        now = max(self.open_weeks) if self.open_weeks else 0
        upcoming = sorted((a for a in self.assessments
                           if isinstance(a["due"], int) and a["due"] >= now),
                          key=lambda a: a["due"])
        # Include the whole final deadline, so reviews and the manual cannot
        # disappear when several submissions share the fourth item's date.
        if len(upcoming) > limit:
            cutoff = upcoming[limit - 1]["due"]
            upcoming = [a for a in upcoming if a["due"] <= cutoff]
        out = "## What is next\n\n" if heading else ""
        if upcoming:
            rows = [[self.link(self.label(a), self.assignment_url(a)),
                     self.deadline(a), f"{a['weight']}%"] for a in upcoming]
            out += table(["Next due", "Date", "Weight"], rows) + "\n"
        else:
            out += "No dated submissions remain; the final review closes the course.\n\n"
        out += (self.link("Full calendar", "/resources/course-policies/#target-teaching-calendar")
                + " — all fifteen weeks with every deadline.\n\n")
        return out

